/**
 * Единица работы — граница транзакции, выраженная в доменных терминах.
 *
 * Application-слою нужно объединить upsert игры и синхронизацию платформ в одну
 * атомарную операцию, но при этом ничего не знать про PostgreSQL, пул соединений
 * и BEGIN/COMMIT. Этот порт даёт ровно такую возможность.
 *
 * `TxContext` намеренно непрозрачен: application получает его от UnitOfWork и
 * передаёт в репозитории, но не может ничего с ним сделать самостоятельно.
 * Так исключается работа с БД в обход границы транзакции.
 */

declare const txBrand: unique symbol;

/** Непрозрачный маркер транзакции. Реализация подставляет своё значение. */
export interface TxContext {
  readonly [txBrand]: true;
}

export interface UnitOfWork {
  /**
   * Выполняет работу в транзакции: при успехе — фиксация, при исключении —
   * откат. Исключение пробрасывается вызывающему после отката.
   */
  withTransaction<T>(work: (tx: TxContext) => Promise<T>): Promise<T>;
}
