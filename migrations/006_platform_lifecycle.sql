-- =============================================================================
-- 006_platform_lifecycle
--
-- Требование: платформа, исчезнувшая из источника, НЕ должна удаляться молча.
--
-- Выбранная стратегия — active/inactive (мягкое отключение):
--   is_active = TRUE   -> платформа присутствовала в последнем снимке
--   is_active = FALSE  -> платформы не было в последнем снимке, данные сохранены
--
-- Почему не физическое удаление: исчезновение платформы чаще означает сбой
-- парсинга или временное изменение вёрстки, а не реальное снятие игры с
-- платформы. Удаление уничтожило бы оценку безвозвратно и незаметно.
--
-- Почему не отдельная таблица снимков: для MVP это избыточно — она потребовала
-- бы истории версий и усложнила все выборки ради данных, которые пока никто
-- не читает. Один флаг решает задачу и обратим.
--
-- last_seen_at позволяет отличить «пропала только что» от «пропала месяц
-- назад» без ведения полноценной истории.
-- =============================================================================

ALTER TABLE game_platforms
    ADD COLUMN is_active BOOLEAN NOT NULL DEFAULT TRUE,
    -- Момент, когда платформа последний раз присутствовала в снимке источника
    ADD COLUMN last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Момент отключения; NULL пока платформа активна
    ADD COLUMN deactivated_at TIMESTAMPTZ;

-- Флаг и метка отключения обязаны быть согласованы: неактивная платформа
-- всегда несёт дату отключения, активная — никогда.
ALTER TABLE game_platforms
    ADD CONSTRAINT game_platforms_active_consistency
        CHECK (
            (is_active AND deactivated_at IS NULL)
            OR (NOT is_active AND deactivated_at IS NOT NULL)
        );

-- Выборки для UI почти всегда касаются активных платформ
CREATE INDEX game_platforms_active_idx
    ON game_platforms (game_id)
    WHERE is_active;

COMMENT ON COLUMN game_platforms.is_active IS
    'Платформа присутствовала в последнем снимке источника. Исчезнувшие '
    'платформы отключаются, а не удаляются (миграция 006)';
COMMENT ON COLUMN game_platforms.last_seen_at IS
    'Когда платформа последний раз встречалась в данных источника';
