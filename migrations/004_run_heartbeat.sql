-- =============================================================================
-- 004_run_heartbeat
-- Поля для достоверного определения "осиротевшего" запуска (orphaned run).
--
-- Проблема: после падения процесса строка runs остаётся в статусе 'running'.
-- Уникальный частичный индекс runs_single_active_idx тогда навсегда блокирует
-- следующий запуск, хотя advisory lock СУБД уже снят.
--
-- Критерий "просто running дольше N минут" отвергнут: длительный, но живой
-- запуск был бы ошибочно признан мёртвым и завершён параллельно с работой.
-- Обоснование выбранного критерия — ADR-0010.
-- =============================================================================

ALTER TABLE runs
    -- Отметка живости: обновляется работающим процессом. Отличает
    -- "долго работает" от "процесс умер".
    ADD COLUMN heartbeat_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Идентификатор владельца — для диагностики: какой процесс вёл запуск.
    -- Не является критерием живости (PID переиспользуются ОС).
    ADD COLUMN owner_id TEXT,

    -- Ключ advisory lock, удерживавшегося запуском. Позволяет проверить
    -- через pg_locks, жив ли держатель, вместо доверия таймауту.
    ADD COLUMN lock_key BIGINT,

    -- Как запуск был завершён: сам процесс или recovery при старте.
    -- Нужно, чтобы отличать штатные завершения от восстановленных.
    ADD COLUMN recovered_at TIMESTAMPTZ,
    ADD COLUMN recovery_reason TEXT;

CREATE INDEX runs_heartbeat_idx ON runs (heartbeat_at) WHERE status = 'running';

COMMENT ON COLUMN runs.heartbeat_at IS
    'Обновляется живым процессом; вторичный критерий orphaned run (ADR-0010)';
COMMENT ON COLUMN runs.lock_key IS
    'Ключ advisory lock: наличие в pg_locks — первичный критерий живости (ADR-0010)';
COMMENT ON COLUMN runs.recovery_reason IS
    'Причина восстановления; дублируется событием в run_events';
